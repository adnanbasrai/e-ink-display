// Board layout: five equal columns -- weather, then four train columns.
//
//   ┌─────────┬─────────┬─────────┬─────────┬─────────┐
//   │   78°   │  (2/3)  │  (4/5)  │   (A)   │  (B/Q)  │  bullet
//   │ 82°/71° │ Nevins  │ Nevins  │Schermer.│ DeKalb  │  station
//   │   ☂     │    7    │    1    │    3    │    0    │  next train, big
//   │  60%    │  15 24  │   8 15  │  12 19  │   9 17  │  following trains
//   ├─────────┴─────────┴─────────┴─────────┴─────────┤
//   │ alert ticker                              3:05 PM│
//   └───────────────────────────────────────────────────┘

